def build_sales_prompt(sales_summary: str) -> str:
    return f"""
あなたは食品業界のトレンドと消費者行動に精通した、経営コンサルタントです。

以下のベーカリーの販売数量データをもとに、現場で即実践できる具体的な提案を3点挙げてください。

【販売データ】
{sales_summary}

【分析の観点】
- 近年の食トレンドや競合業態の動向（例：ドーナツ専門店の減少など）
- ターゲット層別のニーズ（若年層・子育て世代・年配層）
- SNSでの訴求可能性（見た目・素材・ストーリー性）
- 曜日・季節・祝日パターンから読み取れる潜在需要

【出力形式】
箇条書き3点、各1〜2文で簡潔に。
"""


def build_register_sales_prompt(sales_summary: str, *, limited=False) -> str:
    """レジ会計と旧行を営業日で排他集計した差引の意味を明示する。"""
    scope = "数量上位30商品のみ。全商品合計ではありません。" if limited else "全対象商品の集計です。"
    return (
        "ベーカリーの売上について、実行しやすい改善案を3点、簡潔に示してください。\n"
        "旧日次売上と新レジ会計は営業日ごとに排他的に集計しています。"
        "差引数量・差引金額には返金の負数を含みます。"
        "同名でも識別表示が異なる商品は別商品です。"
        "旧商品の金額は現行単価による推計です。"
        f"{scope}\n【商品別実績】\n{sales_summary}"
    )
